"""Every number in the draft is a \\V{key} defined here from raw rows; trace.csv records where each came from.

Raw files under TRACE_revision/raw are only read. Outputs: ../numbers.tex, ../trace.csv.
"""
import csv, hashlib, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
DRAFT = os.path.dirname(HERE)
REV = os.path.abspath(os.path.join(DRAFT, "..", "..", "TRACE_revision"))
sys.path[:0] = [os.path.join(REV, "analysis"), os.path.join(REV, "suites"),
                os.path.join(REV, "baseline", "paper_snapshot", "scripts")]


_SHA = {}


def sha(path):
    if path not in _SHA:
        _SHA[path] = hashlib.sha256(open(path, "rb").read()).hexdigest()[:12]
    return _SHA[path]


class Book:
    def __init__(self):
        self.rows, self.keys = [], set()

    def add(self, key, value, fmt, suite, how, script):
        """fmt: 'pt' signed points 2 dp, 'pt0' unsigned points, 'fr' fraction 3 dp, 'pc' percent 1 dp, 'int', 'raw' (already a string)."""
        assert key not in self.keys, key
        assert all(c.isalnum() or c in ".-_" for c in key), key
        txt = {"pt": lambda v: f"{v:+.2f}", "pt0": lambda v: f"{abs(v):.2f}", "fr": lambda v: f"{v:.3f}",
               "pc": lambda v: f"{100 * v:.1f}", "int": lambda v: f"{int(v):,}".replace(",", "{,}"), "raw": str}[fmt](value)
        txt = txt.replace("-", "$-$") if fmt == "pt" else txt
        self.keys.add(key)
        raw = os.path.join(REV, "raw", suite + ".jsonl")
        self.rows.append(dict(key=key, text=txt, value=value if fmt != "raw" else "", suite=suite, how=how,
                              raw_sha=sha(raw) if os.path.exists(raw) else "", script=os.path.relpath(script, DRAFT)))
        if fmt == "pt":                 # magnitude for sentences that state the direction in words
            self.add(key + ".abs", value, "pt0", suite, how + " (magnitude)", script)

    def write(self):
        with open(os.path.join(DRAFT, "numbers.tex"), "w") as f:
            f.write("% Generated by analysis/build_numbers.py. Do not edit; see trace.csv.\n")
            for r in self.rows:
                f.write("\\expandafter\\def\\csname v@%s\\endcsname{%s}\n" % (r["key"], r["text"]))
        with open(os.path.join(DRAFT, "trace.csv"), "w", newline="") as f:
            w = csv.DictWriter(f, fieldnames=list(self.rows[0])); w.writeheader(); w.writerows(self.rows)
        print(len(self.rows), "numbers written")
